export function getCamera(slug: string): CameraEntry | undefined {
  return CAMERA_CATALOG.find((camera) => camera.slug === slug);
}

export function hasVerifiedLiveCamera(): boolean {
  return getPlayableCameras().some((camera) => camera.streamStatus === "verified");
}

export function canPlayInApp(camera: CameraEntry): boolean {
  return camera.access === "iframe" && Boolean(camera.embedUrl) && (camera.streamStatus === "verified" || camera.streamStatus === "snapshot");
}

/** Keep legacy detail routes, but never offer unavailable or duplicate streams. */
export function getPlayableCameras(): readonly CameraEntry[] {
  const seen = new Set<string>();
  return CAMERA_CATALOG.filter((camera) => {
    if (!canPlayInApp(camera) || !camera.embedUrl || seen.has(camera.embedUrl)) return false;
    seen.add(camera.embedUrl);
    return true;
  });
}
