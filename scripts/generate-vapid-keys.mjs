// One-time script: generate the VAPID key pair for Web Push authentication
// and append it to .env.local. The private key never leaves the script's
// stdout nor the transcript.
//   node scripts/generate-vapid-keys.mjs
import { createRequire } from "node:module";
import { resolve } from "node:path";
import { readFile, writeFile } from "node:fs/promises";

const root = resolve(import.meta.dirname, "..");
const webpush = createRequire(resolve(root, "apps/web/package.json"))("web-push");
const envPath = resolve(root, ".env.local");

const existing = await readFile(envPath, "utf8").catch(() => "");
if (/^VAPID_(PUBLIC|PRIVATE)_KEY=/m.test(existing)) {
  console.error("VAPID keys already present in .env.local; skipping.");
  process.exit(0);
}

const keys = webpush.generateVAPIDKeys();
const subject = process.env.VAPID_SUBJECT ?? "mailto:push@newspoint.bg";
const block = [
  "",
  "# VAPID keys (Web Push) — generated by scripts/generate-vapid-keys.mjs",
  `VAPID_SUBJECT="${subject}"`,
  `VAPID_PUBLIC_KEY="${keys.publicKey}"`,
  `VAPID_PRIVATE_KEY="${keys.privateKey}"`,
  "",
].join("\n");

await writeFile(envPath, existing.replace(/\s*$/, "") + block, "utf8");
console.log("VAPID keys appended to .env.local.");
console.log(`Public key length: ${keys.publicKey.length}`);
console.log(`Private key length: ${keys.privateKey.length}`);