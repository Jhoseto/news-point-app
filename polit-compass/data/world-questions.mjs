// Interleave topics and vary option order so a button position does not identify a political position.
export const questions = Array.from({ length: 5 }, (_, round) => topics.map((topic, column) => {
  const { prompt, options } = topic.rows[round];
  const count = options.length;
  const rotation = (round + column) % count;
  const reverse = (round + column) % 2 === 1;
  const ordered = options.map((_, i) => options[(rotation + (reverse ? -i : i) + count) % count]);
  return { id: topic.id + '-' + round, topic: topic.id, title: topic.title, prompt, options: ordered };
})).flat();
